def generate_report(user_input):

    prompt = build_prompt(user_input)

    inputs = tokenizer(

        prompt,

        return_tensors="pt",

        truncation=True,

        max_length=128
    )

    outputs = model.generate(

        **inputs,

        max_length=256,

        temperature=0.3,

        top_p=0.9,

        do_sample=True
    )

    response = tokenizer.decode(

        outputs[0],

        skip_special_tokens=True
    )

    return response

