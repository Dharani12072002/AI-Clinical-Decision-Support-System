MAX_INPUT = 128
MAX_OUTPUT = 256

def preprocess(example):

    input_text = "medical report generation: " + example["input"]

    target_text = example["output"]

    # INPUT TOKENIZATION
    model_inputs = tokenizer(

        input_text,

        max_length=MAX_INPUT,

        truncation=True,

        padding="max_length"
    )

    # OUTPUT TOKENIZATION
    labels = tokenizer(

        target_text,

        max_length=MAX_OUTPUT,

        truncation=True,

        padding="max_length"
    )

    model_inputs["labels"] = labels["input_ids"]

    return model_inputs

